    /// <summary>The seven music symbols reach the reader as engraved music not as text.</summary>
    [Fact]
    public void the_seven_music_symbols_reach_the_reader_as_engraved_music_not_as_text()
    {
        //Arrange
        string source = File.ReadAllText(
            Path.Combine(_fixture.GeneratedDirectory, "markup-commands.tely"));
        string html = _fixture.HtmlText;

        //Act
        List<string> missingFromSource = new List<string>();
        List<string> presentInHtml = new List<string>();
        foreach (string symbol in Symbols())
        {
            if (!source.Contains(symbol, StringComparison.Ordinal))
            {
                missingFromSource.Add(symbol);
            }

            if (html.Contains(symbol, StringComparison.Ordinal))
            {
                presentInHtml.Add(symbol);
            }
        }

        //Assert
        // All seven are in the port's own generated bytes...
        missingFromSource.Should().BeEmpty();

        // ...and NONE of them is in the rendered text, because every one is markup inside a
        // @lilypond[quote] snippet rather than prose. Asserting the ABSENCE is the point: a
        // future change that put one of them in prose, or added `verbatim' to that snippet,
        // would put a character in front of a text renderer for the first time — and for the
        // PDF that is exactly the question decision D50 is open on. This gate is where such a
        // change announces itself.
        presentInHtml.Should().BeEmpty();

        // The snippet that draws them engraved: no failure was recorded against the file
        // they live in. Without this the gate above would also pass on a manual where that
        // snippet had silently failed and the symbols reached the reader as nothing at all.
        _fixture.Snippets.Failures
            .Where(failure => failure.Location.Contains("markup-commands.tely",
                StringComparison.Ordinal))
            .Should().BeEmpty();
    }

    private static IEnumerable<string> Symbols()
    {
        for (int i = 0; i < MusicSymbols.Length; i += char.IsSurrogatePair(MusicSymbols, i) ? 2 : 1)
        {
            yield return MusicSymbols.Substring(i,
                char.IsSurrogatePair(MusicSymbols, i) ? 2 : 1);
        }
    }

    /// <summary>The engraved music is cropped rather than left on full pages.</summary>
    [Fact]
    public void the_engraved_music_is_cropped_rather_than_left_on_full_pages()
    {
        //Arrange
        List<string> tall = new List<string>();
        List<TexinfoImageReference> sample = _fixture.Html.Result.Images
            .Where(image => image.IsGenerated).Take(200).ToList();

        //Act
        foreach (TexinfoImageReference image in sample)
        {
            Match height = Regex.Match(ReadHead(image.SourcePath, 512), @"height=""([0-9.]+)mm""");
            if (!height.Success
                || double.Parse(height.Groups[1].Value,
                    System.Globalization.CultureInfo.InvariantCulture) > 290)
            {
                tall.Add(image.SourcePath);
            }
        }

        //Assert
        // A4 is 297mm tall. An engraving left on a whole page would place into the manual as
        // a band of whitespace with a line of music at the top of it, and nothing else in
        // this suite would notice — the picture exists, the file has bytes, the count is
        // right. This is the gate on the ly:one-page-breaking directive that wave LD2 added.
        tall.Should().BeEmpty();
        sample.Count.Should().Be(200);
    }

    private static string ReadHead(string path, int count)
    {
        using FileStream stream = File.OpenRead(path);
        byte[] buffer = new byte[count];
        int read = stream.Read(buffer, 0, count);
        return Encoding.UTF8.GetString(buffer, 0, read);
    }

    private static string Report(IReadOnlyList<string> warnings)
        => string.Join("\n", warnings);

    private static string ReportFailures(EngineSnippetRenderer snippets)
    {
        StringBuilder builder = new StringBuilder();
        builder.Append(snippets.FailureCount).Append(" failure(s), ")
            .Append(snippets.DeclineCount).Append(" decline(s):");
        foreach (SnippetFailure failure in snippets.Failures.Take(20))
        {
            builder.Append('\n').Append(failure);
        }

        foreach (string decline in snippets.Declines.Take(20))
        {
            builder.Append('\n').Append(decline);
        }

        return builder.ToString();
    }
