/// <summary>
/// The wave-LD3 gates: the Notation Reference renders to HTML from the port's own generated
/// appendices and the mirrored corpus prose, with its music engraved by the port's own
/// engine.
/// </summary>
public sealed class NotationReferenceRenderTests : IClassFixture<NotationReferenceFixture>
{
    /// <summary>
    /// One marker per generated fragment: a string that appears in THAT fragment's bytes and
    /// in none of the other seventeen, so finding it in the rendered HTML says which file
    /// arrived rather than only that something did.
    /// <para>
    /// Chosen by hand and then CHECKED —
    /// <see cref="each_marker_is_unique_to_its_own_generated_fragment"/> recomputes the
    /// uniqueness from the generated bytes every run, so a generation change that made a
    /// marker ambiguous fails there rather than weakening this gate silently.
    /// </para>
    /// <para>
    /// ⚠ <c>hyphenation.itexi</c> has no entry because it produces NO visible output: it is a
    /// list of TeX hyphenation points. That it resolved is covered by the include-warning
    /// gate instead, which is exactly why that gate needs its own control.
    /// </para>
    /// <para>
    /// ⚠ The two <c>break-align-*</c> fragments are permutations of ONE table — the same
    /// grob and symbol names in both — so no single name can separate them. Their markers are
    /// the column headings, which is the one place the two documents differ in words.
    /// </para>
    /// </summary>
    private static readonly Dictionary<string, string> FragmentMarkers =
        new Dictionary<string, string>(StringComparer.Ordinal)
        {
            { "break-align-grobs-by-symbols.tely", "used by grob(s)" },
            { "break-align-symbols-by-grobs.tely", "break-align symbol(s)" },
            { "context-mod-identifiers.tely", "RemoveAllEmptyStaves" },
            { "css-colors.tely", "crimson" },
            { "identifiers.tely", "Accidental.color" },
            { "markup-commands.tely", "StandaloneRhythmScore" },
            { "markup-list-commands.tely", "point-stencil" },
            { "outside-staff-priorities.tely", "BassFigureAlignmentPositioning" },
            { "paper-sizes.tely", "Australia" },
            { "paper-variables.tely", "auto-first-page-number" },
            { "script-priorities.tely", "AccidentalPlacement" },
            { "standard-colors.tely", "darkyellow" },
            { "type-predicates.tely", "Pango" },
            { "universal-colors.tely", "bluegreen" },
            { "x11-colorN.tely", "antiquewhite1" },
            { "x11-grayN.tely", "gray100" },
            { "x11-unnumbered-colors.tely", "navyblue" },
        };

    /// <summary>
    /// The seven music symbols this manual carries: ♭ ♮ ♯ 𝄪 𝄫 𝄴 𝄵 — three from the Basic
    /// Multilingual Plane and four from the Supplementary Plane.
    /// <para>
    /// ⚠ MEASURED 2026-08-19, AND IT CORRECTS THE PHASE PLAN: they are not prose. All seven
    /// occur inside ONE <c>@lilypond[quote]</c> snippet in the port's own generated
    /// <c>markup-commands.tely</c>, where they are LilyPond markup — <c>\tiny \number ♭</c>
    /// — in a table of Unicode accidental glyphs. The snippet is not <c>verbatim</c>, so its
    /// source is never shown; the seven reach the reader as ENGRAVED MUSIC, drawn by the
    /// port's own engine into an SVG, and no character of them is ever handed to a text
    /// renderer.
    /// </para>
    /// <para>
    /// This matters beyond this gate. Decision D50 is about the seven having no covering font
    /// in the Html2Pdf chain — a question that only arises for text Html2Pdf must SET. On the
    /// same measurement <c>changes.tely</c>'s 𝄴 𝄵 are also inside a <c>@lilypond</c> snippet,
    /// and only <c>music-glossary.tely</c> carries any of them as prose: ♭ four times and ♯
    /// once, in a chord-name multitable. So D50's real footprint is one manual and two
    /// characters, and it is wave LD5's manual rather than this one's or LD4's. The ruling
    /// is Jeremy's; the measurement is recorded here because it is where it was made.
    /// </para>
    /// </summary>
    private const string MusicSymbols = "♭♮♯\U0001d12a\U0001d12b\U0001d134\U0001d135";

    private readonly NotationReferenceFixture _fixture;

    /// <summary>Creates the test class over the shared render.</summary>
    /// <param name="fixture">The one generation-and-render run.</param>
    public NotationReferenceRenderTests(NotationReferenceFixture fixture)
    {
        _fixture = fixture;
    }

    /// <summary>Html render warnings match the frozen baseline exactly.</summary>
    [Fact]
    public void html_render_warnings_match_the_frozen_baseline_exactly()
    {
        //Arrange
        string baselinePath = Path.Combine(
            ToolPaths.ExpectedWarningsDirectory, _fixture.Manual.Name + ".tsv");
        SortedDictionary<string, int> expected = WarningSummary.ReadBaseline(baselinePath);

        //Act
        SortedDictionary<string, int> actual = WarningSummary.Count(_fixture.Html.Warnings);

        //Assert
        // Both directions, as everywhere in this suite: a category that shrank is as much a
        // change to look at as one that grew.
        actual.Should().BeEquivalentTo(expected, Report(_fixture.Html.Warnings));
    }

    /// <summary>Html render produces no include warnings.</summary>
    [Fact]
    public void html_render_produces_no_include_warnings()
    {
        //Arrange
        IReadOnlyList<string> warnings = _fixture.Html.Warnings;

        //Act
        List<string> includeWarnings = warnings
            .Where(w => WarningSummary.CategoryOf(w) == "Include").ToList();

        //Assert
        // ⚠ THIS ZERO IS ONLY MEANINGFUL BESIDE ITS CONTROL. A warning channel that had
        // stopped reporting would produce the same zero. IncludeWarningControlTests renders a
        // document with thirty-nine knowably-absent includes in the same suite and asserts
        // exactly thirty-nine, which is what separates the two readings.
        //
        // What the zero says: every one of this manual's includes resolved — the corpus
        // prose, the vendored GFDL macros, the version stand-in, AND the eighteen files the
        // port generated. The Texinfo repository's own gate carries
        // hasBuildGeneratedIncludes: true for this manual because those eighteen are absent
        // there; here they are supplied from the port's own run, so it flips to false.
        includeWarnings.Should().BeEmpty();
    }

    /// <summary>Html render produces no unresolved reference warnings.</summary>
    [Fact]
    public void html_render_produces_no_unresolved_reference_warnings()
    {
        //Arrange
        IReadOnlyList<string> warnings = _fixture.Html.Warnings;

        //Act
        List<string> referenceWarnings = warnings
            .Where(w => WarningSummary.CategoryOf(w) == "Reference").ToList();

        //Assert
        // The Texinfo repository's own notation baseline tolerated one aggregated Reference
        // warning covering "24 refs into build-generated markup-commands.tely etc." Those
        // targets are supplied here, so this is zero — the same manual, rendered whole
        // because the port produced the parts upstream's build produces.
        referenceWarnings.Should().BeEmpty();
    }

    /// <summary>Every internal link in the html points at an id that exists.</summary>
    [Fact]
    public void every_internal_link_in_the_html_points_at_an_id_that_exists()
    {
        //Arrange
        string html = _fixture.HtmlText;
        HashSet<string> ids = new HashSet<string>(
            Regex.Matches(html, "id=\"([^\"]+)\"").Select(m => m.Groups[1].Value));

        //Act
        List<string> targets = Regex.Matches(html, "href=\"#([^\"]+)\"")
            .Select(m => m.Groups[1].Value).Distinct().ToList();
        List<string> dangling = targets.Where(t => !ids.Contains(t)).ToList();

        //Assert
        // The strongest structural claim available with no fidelity target: not "the render
        // finished" but "every link it wrote goes somewhere". Many of these cross from the
        // corpus prose INTO the port's generated appendices, which is the join this wave is
        // about.
        dangling.Should().BeEmpty();
        targets.Count.Should().BeGreaterThan(1000);
        ids.Count.Should().BeGreaterThan(1000);
    }

    /// <summary>Each marker is unique to its own generated fragment.</summary>
    [Fact]
    public void each_marker_is_unique_to_its_own_generated_fragment()
    {
        //Arrange
        Dictionary<string, string> texts = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (string name in DocumentationGenerator.ExpectedOutputs)
        {
            if (name != "internals.texi")
            {
                texts[name] = File.ReadAllText(
                    Path.Combine(_fixture.GeneratedDirectory, name));
            }
        }

        //Act
        List<string> ambiguous = new List<string>();
        foreach (KeyValuePair<string, string> marker in FragmentMarkers)
        {
            List<string> holders = texts
                .Where(entry => entry.Value.Contains(marker.Value, StringComparison.Ordinal))
                .Select(entry => entry.Key).ToList();
            if (holders.Count != 1 || holders[0] != marker.Key)
            {
                ambiguous.Add(marker.Value + " -> " + string.Join(", ", holders));
            }
        }

        //Assert
        // Recomputed from the bytes every run rather than trusted. A marker that stopped
        // being unique would turn the gate below into "some fragment arrived", and it would
        // do it silently.
        ambiguous.Should().BeEmpty();
        texts.Count.Should().Be(18);
        FragmentMarkers.Count.Should().Be(17);
    }

    /// <summary>Every generated fragment reached the rendered document.</summary>
    [Fact]
    public void every_generated_fragment_reached_the_rendered_document()
    {
        //Arrange
        string html = _fixture.HtmlText;

        //Act
        List<string> missing = FragmentMarkers
            .Where(marker => !html.Contains(marker.Value, StringComparison.Ordinal))
            .Select(marker => marker.Key)
            .ToList();

        //Assert
        // THE WAVE'S OWN CLAIM, stated as content rather than as an absence of warnings:
        // seventeen of the eighteen files the port generated are visibly IN the manual. The
        // eighteenth, hyphenation.itexi, renders nothing by design and is covered by the
        // include-warning gate.
        missing.Should().BeEmpty();
    }

    /// <summary>The manual includes all eighteen generated fragments by name.</summary>
    [Fact]
    public void the_manual_includes_all_eighteen_generated_fragments_by_name()
    {
        //Arrange
        List<string> fragments = DocumentationGenerator.ExpectedOutputs
            .Where(name => name != "internals.texi").ToList();
        string sources = string.Join("\n", Directory
            .EnumerateFiles(Path.Combine(ToolPaths.CorpusDirectory, "en"), "*.ite*",
                SearchOption.AllDirectories)
            .Concat(Directory.EnumerateFiles(Path.Combine(ToolPaths.CorpusDirectory, "en"),
                "*.tely", SearchOption.AllDirectories))
            .Select(File.ReadAllText));

        //Act
        List<string> notIncluded = fragments
            .Where(name => !sources.Contains(
                "@include " + RenderPaths.GeneratedDirectoryName + "/" + name,
                StringComparison.Ordinal))
            .ToList();

        //Assert
        // Read off the corpus rather than remembered, and paired with the zero-Include gate:
        // eighteen include sites that all resolved, against a mirror that CorpusMirrorTests
        // proves holds none of the eighteen files, is what "the manual consumed the PORT's
        // output" means. internals.texi is the nineteenth and is nobody's include — it is a
        // manual in its own right.
        notIncluded.Should().BeEmpty();
        fragments.Count.Should().Be(18);
    }

    /// <summary>The engraver was asked for every snippet and failed none.</summary>
    [Fact]
    public void the_engraver_was_asked_for_every_snippet_and_failed_none()
    {
        //Arrange
        EngineSnippetRenderer snippets = _fixture.Snippets;
        SortedDictionary<string, int> baseline = WarningSummary.ReadBaseline(Path.Combine(
            ToolPaths.ExpectedWarningsDirectory, _fixture.Manual.Name + "-snippets.tsv"));

        //Act
        SortedDictionary<string, int> actual = Program.SnippetCountsOf(
            snippets, _fixture.Html.Result.Images.Count);

        //Assert
        // ⚠ ASKED AND FAILED, NEVER COMPLETION. The package catches a renderer that throws
        // and shows the snippet's source instead, so "the manual rendered" is compatible with
        // every engraving having failed. The baseline freezes what was asked for as well as
        // what came back, so a render that quietly stopped ASKING — a search path that
        // stopped resolving the appendices, say — fails here too.
        actual.Should().BeEquivalentTo(baseline, ReportFailures(snippets));
    }

    /// <summary>Every engraving reached the document as a picture.</summary>
    [Fact]
    public void every_engraving_reached_the_document_as_a_picture()
    {
        //Arrange
        IReadOnlyList<TexinfoImageReference> images = _fixture.Html.Result.Images;

        //Act
        int engraved = images.Count(image => image.IsGenerated);
        int named = images.Count - engraved;

        //Assert
        // The engraver's own count of pictures produced has to equal the document's count of
